let lang = (() => { try { const l = localStorage.getItem(LS_KEY); return l && DICT[l] ? l : "uk"; } catch { return "uk"; } })();
export const getLang = () => lang;
export function setLang(l) {
  if (!DICT[l]) return;
  lang = l;
  try { localStorage.setItem(LS_KEY, l); } catch { /* private mode */ }
  document.documentElement.lang = l;
}

export function t(key, vars) {
  const v = DICT[lang][key] ?? DICT.uk[key] ?? key;
  const s = Array.isArray(v) ? v[0] : v;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m)) : s;
}
// plural form of a 3-form word (1 / 2-4 / 5+), same rule for Ukrainian and Russian
export function tp(key, n) {
  const forms = DICT[lang][key] || DICT.uk[key];
  const m = n % 100, d = n % 10;
  return forms[m > 10 && m < 20 ? 2 : d === 1 ? 0 : d > 1 && d < 5 ? 1 : 2];
}

// Fill static markup: data-i18n (text), data-i18n-html (own trusted markup), data-i18n-ph, data-i18n-aria
export function applyStatic(root = document) {
  root.querySelectorAll("[data-i18n]").forEach(e => { e.textContent = t(e.dataset.i18n); });
  root.querySelectorAll("[data-i18n-html]").forEach(e => { e.innerHTML = t(e.dataset.i18nHtml); });
  root.querySelectorAll("[data-i18n-ph]").forEach(e => { e.placeholder = t(e.dataset.i18nPh); });
  root.querySelectorAll("[data-i18n-aria]").forEach(e => { e.setAttribute("aria-label", t(e.dataset.i18nAria)); });
  document.documentElement.lang = lang;
}

